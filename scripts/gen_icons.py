#!/usr/bin/env python3
"""Copy the Lucide icon font into BuzzahBuddy and generate the glyph constants.

The design system pins Lucide 1.55.0 and sanctions the lucide-static package:

  npm pack lucide-static@1.55.0 && tar -xzf lucide-static-1.55.0.tgz
  python3 scripts/gen_icons.py ./package

Add a glyph to GLYPHS only after its meaning has a row in the design system's
iconography table.
"""
import json
import shutil
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
APP = REPO / "BuzzahBuddy"
VERSION = "1.55.0"
GLYPHS = ["play", "pause", "square", "hand", "bluetooth", "battery-full", "battery-medium", "battery-low",
          "activity", "settings", "circle-check", "triangle-alert", "octagon-alert", "info", "check", "plus",
          "minus", "chevron-right", "refresh-cw", "cpu", "radar", "signal-low",
          "signal-medium", "signal-high", "save", "vibrate", "hard-drive-download", "unplug"]


def main():
    pkg = Path(sys.argv[1]).resolve()
    meta = json.loads((pkg / "package.json").read_text())
    if meta["version"] != VERSION:
        sys.exit(f"lucide-static {meta['version']} found, {VERSION} pinned")
    codepoints = json.loads((pkg / "font/codepoints.json").read_text())
    missing = [g for g in GLYPHS if g not in codepoints]
    if missing:
        sys.exit(f"missing glyphs: {missing}")
    fonts = APP / "Resources/Fonts"
    shutil.copy(pkg / "font/lucide.ttf", fonts / "lucide.ttf")
    shutil.copy(pkg / "LICENSE", fonts / "licenses/LICENSE-lucide.txt")
    lines = [f"// Generated by scripts/gen_icons.py from lucide-static {VERSION}. Do not edit.",
             "namespace BuzzahBuddy.Helpers;", "",
             "/// <summary>Lucide glyphs for the <c>Lucide</c> font (FontImageSource / IconLabel).</summary>",
             "public static class LucideIcons", "{"]
    for g in GLYPHS:
        name = "".join(p.capitalize() for p in g.split("-"))
        lines.append(f'    public const string {name} = "\\u{codepoints[g]:04X}";')
    lines += ["}", ""]
    (APP / "Helpers/LucideIcons.g.cs").write_text("\n".join(lines))
    print(f"copied lucide.ttf, wrote Helpers/LucideIcons.g.cs ({len(GLYPHS)} glyphs)")


if __name__ == "__main__":
    main()
