#!/usr/bin/env python3
"""Generate BuzzahBuddy's design tokens from the BlueBuzzah design system.

Reads the design system's tokens.json and writes the app's theme dictionaries,
size tokens, type styles, the C# color table and Android color resources. The
outputs are committed; rerun this after the design system changes, never edit
the outputs by hand.

Usage: python3 scripts/gen_design_tokens.py [--ds PATH]
       (PATH defaults to ../../.claude/skills/bluebuzzah-design-system)
"""
import argparse
import json
import re
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
APP = REPO / "BuzzahBuddy"
THEMES = [("light", "Light"), ("dark", "Dark"), ("light-hc", "LightHc"), ("dark-hc", "DarkHc")]

# Family + weight -> resource key holding the font alias (Typography.ApplyFontWeights sets them).
FONT_KEYS = {("display", 500): "FontDisplay500", ("display", 600): "FontDisplay600",
             ("sans", 400): "FontSans400", ("sans", 700): "FontSans700", ("mono", 400): "FontMono400"}


def pascal(name):
    return "".join(part.capitalize() for part in name.split("-"))


def px(value):
    return float(value.removesuffix("px"))


def num(v):
    return str(int(v)) if float(v).is_integer() else f"{v:g}"


def parse_rgba(text):
    m = re.fullmatch(r"rgba\((\d+),\s*(\d+),\s*(\d+),\s*([\d.]+)\)", text.strip())
    r, g, b, a = int(m[1]), int(m[2]), int(m[3]), float(m[4])
    return f"#{round(a * 255):02X}{r:02X}{g:02X}{b:02X}", (r, g, b, a)


def hex_argb(value):
    """CSS color -> #RRGGBB or #AARRGGBB (MAUI order)."""
    return parse_rgba(value)[0] if value.startswith("rgba") else value.upper()


def split_layers(value):
    return [p.strip() for p in re.split(r",\s*(?![^()]*\))", value)]


def shadow(value):
    """Bundle CSS shadow -> (x, y, blur, color hex, opacity); outer layer with the largest blur."""
    if value == "none":
        return 0, 0, 0, "#000000", 0
    best = None
    for layer in split_layers(value):
        if layer.startswith("inset"):
            continue
        m = re.fullmatch(r"(-?\d+)(?:px)? (-?\d+)(?:px)? (\d+)(?:px)? (rgba\(.*\))", layer)
        x, y, blur = int(m[1]), int(m[2]), int(m[3])
        _, (r, g, b, a) = parse_rgba(m[4])
        if best is None or blur > best[2]:
            best = (x, y, blur, f"#{r:02X}{g:02X}{b:02X}", a)
    return best


def header(version, style="xml"):
    text = f"Generated by scripts/gen_design_tokens.py from bluebuzzah-design-system {version}. Do not edit."
    return f"<!-- {text} -->" if style == "xml" else f"// {text}"


def write(path, text, bom=False, crlf=True):
    path.parent.mkdir(parents=True, exist_ok=True)
    body = text.replace("\n", "\r\n") if crlf else text
    path.write_bytes(("﻿" if bom else "").encode() + body.encode())
    print(f"wrote {path.relative_to(REPO)}")


def theme_colors(tokens):
    """{theme_id: {Key: hex}} for every non-ramp color token; aliases like {brand} resolved."""
    out = {tid: {} for tid, _ in THEMES}
    by_name = {t["name"]: t for t in tokens}
    for t in tokens:
        if t["name"].startswith("buzz-"):
            continue
        value = t["value"]
        if isinstance(value, str) and value.startswith("{"):
            value = by_name[value.strip("{}")]["value"]
        for tid, _ in THEMES:
            v = value[tid] if isinstance(value, dict) else value
            out[tid][pascal(t["name"])] = hex_argb(v)
    return out


def gen_themes(ds, colors, version):
    for tid, name in THEMES:
        lines = [f'<?xml version="1.0" encoding="UTF-8" ?>', header(version),
                 '<ResourceDictionary xmlns="http://schemas.microsoft.com/dotnet/2021/maui"',
                 '                    xmlns:x="http://schemas.microsoft.com/winfx/2009/xaml"',
                 f'                    x:Class="BuzzahBuddy.Resources.Styles.Themes.{name}Theme">']
        for key, value in colors[tid].items():
            lines.append(f'    <Color x:Key="{key}">{value}</Color>')
        for s in ds["shadow"]["tokens"]:
            if s["name"] == "focus-ring":
                continue
            x, y, blur, color, opacity = shadow(s["value"][tid])
            lines.append(f'    <Shadow x:Key="{pascal(s["name"])}" Brush="{color}" Offset="{x},{y}" '
                         f'Radius="{blur}" Opacity="{num(opacity)}" />')
        lines.append(f'    <x:Double x:Key="HcBorderWidth">{2 if tid.endswith("-hc") else 0}</x:Double>')
        lines.append("</ResourceDictionary>\n")
        base = APP / "Resources/Styles/Themes" / f"{name}Theme.g.xaml"
        write(base, "\n".join(lines), bom=True)
        write(base.with_name(base.name + ".cs"), "\n".join([
            header(version, "cs"),
            "namespace BuzzahBuddy.Resources.Styles.Themes;", "",
            f"public partial class {name}Theme : ResourceDictionary", "{",
            f"    public {name}Theme() => InitializeComponent();", "}", ""]), crlf=False)


def gen_tokens(ds, version):
    lines = ['<?xml version="1.0" encoding="UTF-8" ?>', header(version),
             '<ResourceDictionary xmlns="http://schemas.microsoft.com/dotnet/2021/maui"',
             '                    xmlns:x="http://schemas.microsoft.com/winfx/2009/xaml">']
    for group in ("spacing", "size", "borderWidth"):
        for t in ds[group]["tokens"]:
            if not t["value"].endswith("px"):
                continue  # rem widths (content-max, prose-max) are web-only
            lines.append(f'    <x:Double x:Key="{pascal(t["name"])}">{num(px(t["value"]))}</x:Double>')
    for t in ds["radius"]["tokens"]:
        v = num(px(t["value"]))
        lines.append(f'    <CornerRadius x:Key="{pascal(t["name"])}">{v}</CornerRadius>')
        lines.append(f'    <x:Int32 x:Key="{pascal(t["name"])}Int">{v}</x:Int32>')
    for t in ds["duration"]["tokens"]:
        lines.append(f'    <x:Int32 x:Key="{pascal(t["name"])}">{int(t["value"].removesuffix("ms"))}</x:Int32>')
    lines.append("</ResourceDictionary>\n")
    write(APP / "Resources/Styles/Tokens.g.xaml", "\n".join(lines), bom=True)


def gen_type(ds, version):
    lines = ['<?xml version="1.0" encoding="UTF-8" ?>', header(version),
             '<ResourceDictionary xmlns="http://schemas.microsoft.com/dotnet/2021/maui"',
             '                    xmlns:x="http://schemas.microsoft.com/winfx/2009/xaml"',
             '                    xmlns:helpers="clr-namespace:BuzzahBuddy.Helpers">']
    for group in ds["type"]["groups"]:
        for s in group["styles"]:
            family = s.get("family", group["family"])
            size = float(s["fontSize"].removesuffix("rem")) * 16
            line_height = float(s["lineHeight"].removesuffix("rem")) * 16
            lines.append(f'    <Style x:Key="Type{pascal(s["name"])}" TargetType="Label">')
            lines.append(f'        <Setter Property="FontFamily" Value="{{DynamicResource {FONT_KEYS[(family, s["fontWeight"])]}}}" />')
            lines.append(f'        <Setter Property="FontSize" Value="{num(size)}" />')
            lines.append(f'        <Setter Property="LineHeight" Value="{line_height / size:.4g}" />')
            if "letterSpacing" in s:
                em = float(s["letterSpacing"].removesuffix("em"))
                lines.append(f'        <Setter Property="CharacterSpacing" Value="{em * size:.4g}" />')
            lines.append('        <Setter Property="TextColor" Value="{DynamicResource Ink}" />')
            if s["name"] == "overline":
                lines.append('        <Setter Property="TextTransform" Value="Uppercase" />')
            if s["name"] in ("metric-xl", "metric"):
                lines.append('        <Setter Property="helpers:Typography.TabularNumbers" Value="True" />')
            lines.append("    </Style>")
    lines.append("</ResourceDictionary>\n")
    write(APP / "Resources/Styles/Type.g.xaml", "\n".join(lines), bom=True)


def gen_csharp(colors, version):
    lines = [header(version, "cs"), "using Microsoft.Maui.Graphics;", "", "namespace BuzzahBuddy.Helpers;", "",
             "/// <summary>Design-system colors per theme, for code that can't reach app resources.</summary>",
             "public static class DesignColors", "{",
             "    public static readonly IReadOnlyDictionary<string, IReadOnlyDictionary<string, Color>> Themes =",
             "        new Dictionary<string, IReadOnlyDictionary<string, Color>>", "        {"]
    for tid, _ in THEMES:
        lines.append(f'            ["{tid}"] = new Dictionary<string, Color>')
        lines.append("            {")
        for key, value in colors[tid].items():
            lines.append(f'                ["{key}"] = Color.FromArgb("{value}"),')
        lines.append("            },")
    lines += ["        };", "}", ""]
    write(APP / "Helpers/DesignColors.g.cs", "\n".join(lines), crlf=False)


def gen_android(colors, version):
    for folder, tid in (("values", "light"), ("values-night", "dark")):
        c = colors[tid]
        pairs = [("colorPrimary", c["Brand"]), ("colorPrimaryDark", c["Surface"]), ("colorAccent", c["Brand"]),
                 ("colorBackground", c["Surface"]), ("colorSurface", c["SurfaceRaised"]),
                 ("ic_launcher_background", c["IconGround"])]
        body = ['<?xml version="1.0" encoding="utf-8"?>', header(version), "<resources>"]
        body += [f'    <color name="{n}">{v}</color>' for n, v in pairs]
        body.append("</resources>\n")
        write(APP / f"Platforms/Android/Resources/{folder}/colors.xml", "\n".join(body))


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--ds", type=Path, default=REPO / "../../.claude/skills/bluebuzzah-design-system")
    ds_dir = parser.parse_args().ds.resolve()
    ds = json.loads((ds_dir / "tokens.json").read_text())
    m = re.search(r"version `([^`]+)`", (ds_dir / "SKILL.md").read_text())
    version = m[1] if m else f"tokens v{ds['version']}"
    print(f"design system {version} from {ds_dir}")
    colors = theme_colors(ds["color"]["tokens"])
    gen_themes(ds, colors, version)
    gen_tokens(ds, version)
    gen_csharp(colors, version)
    gen_android(colors, version)


if __name__ == "__main__":
    main()
